window.rikaiT = function rikaiT(lang, key, vars) {
  const dict = window.RIKAI_I18N[lang] || window.RIKAI_I18N.en;
  let str = dict[key] || window.RIKAI_I18N.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replaceAll(`{${k}}`, String(vars[k]));
    });
  }
  return str;
};
